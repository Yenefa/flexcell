#!/usr/bin/env python3
"""Tests that the capability ladder cannot drift away from the archived evidence.

THE FAILURE THIS PREVENTS: the document said of itself "this is not a hand-written status
table, every line can be reproduced with one command" - and then drifted to reporting 17
batches and 116 tests while the repository held 32 and 222. It also still asserted a
false-success zero under a banner that had already retracted that zero. A status document
that drifts is worse than none, because it is believed.

So the numbers are regenerated by a script, and these tests fail when the committed document
no longer agrees with the archive.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "CAPABILITY_LADDER.md"
INDEX = ROOT / "setup" / "acceptance" / "evobot_evidence_index.json"
GEN = ROOT / "experiments" / "baselines" / "capability_ladder.py"


def _doc():
    return DOC.read_text(encoding="utf-8")


def test_the_document_declares_itself_generated():
    text = _doc()
    assert "capability_ladder.py" in text
    assert "请勿手工编辑" in text or "generated" in text.lower()


def test_the_generator_exists_and_runs():
    assert GEN.exists()
    r = subprocess.run([sys.executable, str(GEN)], cwd=str(ROOT),
                       capture_output=True, text=True, timeout=300)
    assert r.returncode == 0, (r.stdout or "")[-800:] + (r.stderr or "")[-800:]


def test_the_batch_counts_match_the_evidence_index():
    _regenerate()
    idx = json.loads(INDEX.read_text(encoding="utf-8"))
    text = _doc()
    # both counts must appear as the index reports them
    assert "| 证据批次（有效） | %s |" % idx["live"] in text, idx["live"]
    assert "| 证据批次（已取代但保留） | %s |" % idx["superseded"] in text
    assert "| 批次验证器失败数 | **%s** |" % idx["verifier_failures"] in text


def _regenerate():
    """Regenerate first, so this test does not depend on another test having run yet.

    Relying on order would make the suite pass in one order and fail in another - the
    same class of hidden coupling that let a pipeline step silently not run.
    """
    subprocess.run([sys.executable, str(GEN)], cwd=str(ROOT),
                   capture_output=True, text=True, timeout=300)


def test_the_test_count_matches_the_actual_collection():
    _regenerate()
    r = subprocess.run([sys.executable, "-m", "pytest", "benchmark/tests",
                        "--collect-only", "-q", "-p", "no:warnings"],
                       cwd=str(ROOT), capture_output=True, text=True)
    n = 0
    for line in reversed((r.stdout or "").strip().splitlines()):
        if "collected" in line:
            n = int(line.split()[0])
            break
    assert n > 0
    assert "| 离线测试 | **%d** |" % n in _doc(), n


def test_both_failure_directions_are_reported():
    """A single-direction report is the defect that hid false failure for many rounds."""
    text = _doc()
    assert "False Success" in text
    assert "False Failure" in text


def test_the_document_does_not_assert_an_unqualified_zero():
    text = _doc()
    # wherever a zero false-success is stated, the caveat must be stated with it
    assert "不可测量" in text or "区间上界不为 0" in text


def test_pending_proposals_are_reported_as_unapproved():
    text = _doc()
    if (ROOT / "evolution" / "proposals" / "release_confirmation_preregistration.json").exists():
        assert "False" in text or "false" in text
        assert "待人工批准" in text


def test_the_document_states_that_failures_do_not_reproduce():
    """A pass rate without this caveat invites the reader to treat it as a rate over tasks."""
    _regenerate()
    text = _doc()
    assert "失败不可复现" in text
    assert "两次都失败" in text
    assert "25%" in text
    assert "机制证据" in text
